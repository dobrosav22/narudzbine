// Regenerates i18n/resources.gen.ts from i18n/messages/<language>/<namespace>.json.
// One file per namespace keeps feature work from colliding in one huge JSON file.
// Run after adding a namespace: pnpm --filter @repo/core i18n:index
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const i18n = join(dirname(fileURLToPath(import.meta.url)), '..', 'i18n');
const languages = { en: 'en', 'sr-Latn': 'srLatn' };
const namespaces = readdirSync(join(i18n, 'messages', 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort();

for (const language of Object.keys(languages)) {
  const present = new Set(readdirSync(join(i18n, 'messages', language)).map((f) => f.slice(0, -5)));
  const missing = namespaces.filter((n) => !present.has(n));
  if (missing.length) throw new Error(`${language} is missing namespaces: ${missing.join(', ')}`);
}

const ident = (language, ns) => `${languages[language]}_${ns.replace(/[^A-Za-z0-9]/g, '_')}`;
const lines = ['// GENERATED by scripts/i18n-index.mjs — do not edit. Add namespaces under messages/<language>/.', ''];
for (const language of Object.keys(languages))
  for (const ns of namespaces) lines.push(`import ${ident(language, ns)} from './messages/${language}/${ns}.json';`);
lines.push('');
for (const [language, variable] of Object.entries(languages)) {
  lines.push(`export const ${variable} = {`);
  for (const ns of namespaces) lines.push(`  ${JSON.stringify(ns)}: ${ident(language, ns)},`);
  lines.push('};', '');
}
writeFileSync(join(i18n, 'resources.gen.ts'), lines.join('\n'));
console.log(`resources.gen.ts: ${namespaces.length} namespaces`);
